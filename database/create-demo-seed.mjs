// Generate a repeatable, development-only seed from the exact UI fixtures.
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import { MEMBERSHIP_PLANS } from '../apps/studio/app/_lib/membership.js';

const data = JSON.parse(readFileSync(new URL('../apps/studio/app/_lib/showcase-data.json', import.meta.url), 'utf8'));
const quote = value => value == null ? 'NULL' : typeof value === 'boolean' || typeof value === 'number' ? String(value) : `'${String(value).replaceAll("'", "''")}'`;
const id = key => {
  const h = createHash('sha256').update(`snowlink-demo:${key}`).digest('hex');
  return `${h.slice(0, 8)}-${h.slice(8, 12)}-5${h.slice(13, 16)}-8${h.slice(17, 20)}-${h.slice(20, 32)}`;
};
const sql = ['-- Generated by node database/create-demo-seed.mjs. Demo accounts cannot log in.', '-- Apply only to a fresh development database, after 001_schema.sql.', 'BEGIN;', 'SET LOCAL search_path = snowlink, public;'];
function insert(table, row) { sql.push(`INSERT INTO ${table} (${Object.keys(row).join(', ')}) VALUES (${Object.values(row).map(quote).join(', ')}) ON CONFLICT DO NOTHING;`); }

for (const creator of data.creators) {
  const userId = id(`user:${creator.id}`), workspace = id(`workspace:${creator.id}`);
  insert('users', { id: userId, username: `demo.${creator.id}`, role: 'demo' });
  insert('creator_profiles', { user_id: userId, handle: creator.id, display_name: creator.name, bio: creator.bio, tagline: creator.tagline, is_public: true, is_demo: true });
  insert('workspaces', { id: workspace, owner_id: userId, name: `${creator.name}의 목업 작업실` });
  insert('assets', { id: id(`asset:${creator.id}`), workspace_id: workspace, storage_key: creator.image.slice(1), mime_type: 'image/png', width: 1536, height: 1024, source: 'demo', provenance: JSON.stringify({ generatedWith: 'image_gen', fictional: true }) });
}
for (const work of data.works) {
  const workspace = id(`workspace:${work.creatorId}`);
  if (work.kind === 'character') {
    insert('characters', { id: id(`character:${work.id}`), workspace_id: workspace, name: work.title, description: work.summary, attributes: JSON.stringify(work.details) });
    insert('character_sheets', { id: id(`sheet:${work.id}`), workspace_id: workspace, character_id: id(`character:${work.id}`), asset_id: id(`asset:${work.creatorId}`) });
  }
  if (work.kind === 'novel') {
    const story = id(`story:${work.id}`);
    insert('projects', { id: id(`project:${work.id}`), workspace_id: workspace, title: work.title, format: 'novel', stage: 'review' });
    insert('stories', { id: story, workspace_id: workspace, project_id: id(`project:${work.id}`), premise: work.summary, planned_episodes: work.chapters.length });
    for (const chapter of work.chapters) {
      const episode = id(`episode:${work.id}:${chapter.number}`);
      insert('episodes', { id: episode, workspace_id: workspace, story_id: story, number: chapter.number, title: chapter.title, body: chapter.body, status: 'ready' });
      insert('episode_revisions', { episode_id: episode, workspace_id: workspace, story_id: story, version: 1, body: chapter.body, plot: '' });
    }
  }
}
for (const work of data.works) {
  const workspace = id(`workspace:${work.creatorId}`), publication = id(`publication:${work.id}`);
  insert('publications', {
    id: publication, workspace_id: workspace, creator_id: id(`user:${work.creatorId}`), slug: work.id, kind: work.kind,
    title: work.title, summary: work.summary, tags: `{${work.tags.map(tag => `"${tag.replaceAll('"', '\\"')}"`).join(',')}}`,
    cover_public_path: work.image, cover_alt: work.imageAlt, public_body: work.body || '', public_character_details: JSON.stringify(work.details || []),
    visibility: work.visibility, status: work.status, published_at: work.publishedAt, is_demo: true,
    source_project_id: work.kind === 'novel' ? id(`project:${work.id}`) : null,
    source_character_id: work.kind === 'character' ? id(`character:${work.id}`) : null,
  });
  for (const chapter of work.chapters || []) insert('publication_chapters', { publication_id: publication, workspace_id: workspace, number: chapter.number, title: chapter.title, body: chapter.body });
}
for (const work of data.works) {
  for (const related of work.relatedIds) insert('publication_links', { publication_id: id(`publication:${work.id}`), related_id: id(`publication:${related}`), workspace_id: id(`workspace:${work.creatorId}`) });
  if (work.kind === 'novel') {
    for (const related of work.relatedIds.filter(slug => data.works.find(item => item.id === slug)?.kind === 'character')) insert('project_characters', { workspace_id: id(`workspace:${work.creatorId}`), project_id: id(`project:${work.id}`), character_id: id(`character:${related}`) });
  }
}
for (const plan of MEMBERSHIP_PLANS) insert('membership_plans', { code: plan.id, name: plan.name, state: plan.id === 'free' ? 'free' : 'coming_soon', monthly_price_krw: plan.id === 'free' ? 0 : null, yearly_price_krw: plan.id === 'free' ? 0 : null, proposed_features: JSON.stringify(plan.features) });
sql.push('COMMIT;', '');
writeFileSync(new URL('./002_demo_seed.sql', import.meta.url), sql.join('\n'));
console.log(`Created demo seed: ${data.creators.length} creators, ${data.works.length} publications, ${data.works.flatMap(work => work.chapters || []).length} chapters.`);
